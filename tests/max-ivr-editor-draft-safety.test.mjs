import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const read=p=>readFileSync(p,"utf8");
const common=read("artifacts/api-server/src/lib/max-ivr-editor.ts");
const api=read("artifacts/api-server/src/routes/max-ivr-editor.ts");
const phone=read("artifacts/api-server/src/lib/max-ivr-phone-editor.ts");
const recording=read("artifacts/api-server/src/lib/max-ivr-phone-recording.ts");
const shared=read("artifacts/api-server/src/lib/signalwire-shared-ivr.ts");
const routes=read("artifacts/api-server/src/routes/index.ts");
const ui=read("artifacts/gavhah/src/components/admin/max-ivr-builder.tsx");
const studio=read("artifacts/gavhah/src/components/admin/max-voice-studio.tsx");
const admin=read("artifacts/gavhah/src/pages/admin/index.tsx");
test("MAX advanced builder is mounted only in super-admin UI",()=>{
 assert.match(admin,/user\?\.role === "super_admin"/);
 assert.match(admin,/<MaxIvrBuilder \/>/);
 assert.match(routes,/router\.use\(maxIvrEditorRouter\)/);
 assert.match(api,/getCurrentSessionUser/);
 assert.match(api,/user\.role!=="super_admin"/);
 assert.match(api,/sameOrigin\(req\)/);
});
test("all edits are draft-only, protected extensions are reserved",()=>{
 for(const p of ["4444","55555","8899"])assert.ok(common.includes(p));
 assert.match(common,/pathAllowed/);
 assert.match(common,/MAX_EDITOR_ACTIONS/);
 assert.match(common,/BUILTINS/);
 assert.match(common,/VOICES/);
 assert.match(common,/gavhah_max_ivr_draft_nodes/);
 assert.match(common,/gavhah_max_ivr_draft_buttons/);
 assert.match(ui,/Array\.from\(\{length:9\}/);
 assert.match(ui,/config\.action==="submenu"/);
 assert.match(ui,/read_message/);
 assert.match(studio,/draft_audio|voice-studio\/.*audio|audio\/wav/);
 assert.doesNotMatch(common,/voice-switch\/apply|api\/relay\/rest\/phone_numbers/);
 assert.doesNotMatch(recording,/voice-switch\/apply|SignalWire.*PATCH/);
});
test("telephone editor cannot authenticate by caller ID alone",()=>{
 assert.match(phone,/securityHash\("login"/);
 assert.match(phone,/used_at IS NULL/);
 assert.match(phone,/stage==="login"/);
 assert.match(phone,/activeAdmin\(member\)/);
 assert.match(phone,/failed_attempts>=3/);
 assert.match(common,/expires_at/);
 assert.match(shared,/checkSignalWireSignature/);
 assert.ok(shared.indexOf("checkSignalWireSignature")<shared.indexOf("tryMaxPhoneEditor({"));
 assert.match(shared,/digits!=="55555"/);
 assert.match(shared,/!state\|\|!state\.path/);
});
test("phone recordings use only a fixed SignalWire project URL",()=>{
 assert.match(recording,/RecordingSid/);
 assert.match(recording,/\.signalwire\.com\/api\/laml/);
 assert.match(recording,/redirect:"error"/);
 assert.match(recording,/4\*1024\*1024/);
 assert.match(recording,/NOT change any live extension/i);
 assert.doesNotMatch(recording,/fetch\(recordingUrl/i);
 assert.match(phone,/privateMaxRecording/);
 assert.match(phone,/beginMaxRecording/);
 assert.match(ui,/phoneEditorExtension/);
});
